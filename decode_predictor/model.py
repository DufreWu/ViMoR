"""
model
==========
PredictorHead – Soft Label Regression head for output length prediction.

Architecture
------------
Input  : pooled hidden-state vector z ∈ ℝ^d  (from FeatureExtractor)
Layers : Linear(d, d//2) → LayerNorm → ReLU → Dropout(0.1) → Linear(d//2, K)
Output : (logits ∈ ℝ^K, pred ∈ ℝ)  where pred = Σ_k softmax(logits)_k · c_k

The bin centres c_k are computed from the 1st–99th percentile range of training
targets and registered as a non-trainable buffer.

Loss (combined in DecodeLenPredictorTrainer)
------------------------------
  ℒ = λ · KL(log_softmax(logits) ‖ soft_labels(y))
    + (1−λ) · MSE(pred, y)

Soft labels are generated by ``PredictorHead.soft_labels``: the ground-truth length
is mapped to a bin index *i*, and the soft label vector is softmax(-|j-i|) over
all bins j, giving a peaked distribution centred on the correct bin.
"""

from __future__ import annotations

import torch
import torch.nn as nn
import torch.nn.functional as F

class PredictorHead(nn.Module):
    """
    Lightweight MLP head for LLM output length prediction via soft label
    regression over discretised length bins.

    Parameters
    ----------
    input_dim : int
        Dimensionality of the input representation (backbone hidden size *d*).
    num_bins : int
        Number of discrete length bins *K* to regress over. Default: 20.
    target_range : tuple[float, float]
        ``(min_val, max_val)`` define the binning range. Values are typically
        set to the (1st, 99th) percentile of training target lengths.
    dropout : float
        Dropout probability applied after the first hidden layer. Default: 0.1.
    """

    def __init__(
        self,
        input_dim: int,
        num_bins: int = 20,
        target_range: tuple[float, float] = (0.0, 1024.0),
        dropout: float = 0.1,
    ) -> None:
        super().__init__()
        self.num_bins = num_bins
        self.min_val, self.max_val = target_range

        hidden_dim = input_dim // 2

        self.fc = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.LayerNorm(hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, num_bins),
        )

        # Bin centres (non-trainable buffer)
        width = (self.max_val - self.min_val) / self.num_bins
        centers = self.min_val + (torch.arange(num_bins).float() + 0.5) * width
        self.register_buffer("bin_centers", centers.unsqueeze(0))  # (1, K)

    # ──────────────────────────────────────────────────────────────────────
    # Forward
    # ──────────────────────────────────────────────────────────────────────

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        """
        Parameters
        ----------
        x : torch.Tensor of shape (N, d)

        Returns
        -------
        logits : torch.Tensor of shape (N, K)
            Raw (un-normalised) bin scores.
        pred   : torch.Tensor of shape (N,)
            Expected length = Σ_k softmax(logits)_k · c_k.
        """
        logits = self.fc(x)                            # (N, K)
        probs = F.softmax(logits, dim=-1)              # (N, K)
        pred = torch.sum(probs * self.bin_centers, dim=-1)  # (N,)
        return logits, pred

    # ──────────────────────────────────────────────────────────────────────
    # Soft-label generation (used during training)
    # ──────────────────────────────────────────────────────────────────────

    def soft_labels(self, y: torch.Tensor) -> torch.Tensor:
        """
        Convert a batch of ground-truth lengths into soft probability vectors
        over bins via softmax(-|j - i|), where *i* is the ground-truth bin
        of each sample and *j* ranges over 0 … K-1.

        Parameters
        ----------
        y : torch.Tensor of shape (N,)  - ground-truth output lengths.

        Returns
        -------
        soft : torch.Tensor of shape (N, K) - soft label distributions.
        """
        y = torch.clamp(y, self.min_val, self.max_val)
        width = (self.max_val - self.min_val) / self.num_bins
        target_bins = torch.floor((y - self.min_val) / width)
        target_bins = torch.clamp(target_bins, 0, self.num_bins - 1).long()  # (N,)

        j = torch.arange(self.num_bins, device=y.device).unsqueeze(0)    # (1, K)
        i = target_bins.unsqueeze(1)                                     # (N, 1)
        dist = torch.abs(j - i).float()                                  # (N, K)
        return F.softmax(-dist, dim=-1)                                  # (N, K)